/**
 * Writes supabase/seed.sql from the demo data, so the database and the mock fallback match.
 * Run: bun run db:seed-sql
 */
import * as mock from "../lib/mock";
import { FARM_ID, market, profileFields, sectionConfirmations, signals, SNAPSHOT_AT } from "../lib/profile/fenland-ridge";
import { makeSnapshot, measureSignal } from "../lib/profile/risk-profile";

const SNAPSHOT_ID = "00000000-0000-4000-8000-000000000001";
const ASSESSMENT_ID = "00000000-0000-4000-8000-000000000002";

const q = (v: unknown) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const j = (v: unknown) => `${q(JSON.stringify(v))}::jsonb`;
const n = (v: number | null | undefined) => (v === null || v === undefined ? "null" : String(v));
const rows = (r: string[]) => r.join(",\n  ");

const snapshot = makeSnapshot({
  id: SNAPSHOT_ID,
  version: 1,
  takenAt: SNAPSHOT_AT,
  reason: "Onboarding confirmed",
  fields: profileFields,
  market,
});

/** Pending changes in the mock carry display times; give them real timestamps for the database. */
const receivedAt: Record<string, string> = {
  "pc-nitrogen": "2026-11-07T06:00:00Z",
  "pc-osr-yield": "2026-11-06T17:42:00Z",
  "pc-wheat-sold": "2026-11-05T19:03:00Z",
  "pc-lender": "2026-11-04T09:15:00Z",
  "pc-overdraft": "2026-11-03T14:20:00Z",
};

const sql = `-- Generated by scripts/generate-seed.ts. Do not edit by hand: change the demo data and re-run.
-- Fictional demo farm: Fenland Ridge Farm Ltd. Safe to run more than once.

begin;

delete from farms where id = ${q(FARM_ID)};
delete from signals where id in (${signals.map((s) => q(s.id)).join(", ")});

insert into farms (id, name, hectares, location, crops) values
  (${q(FARM_ID)}, ${q(mock.farm.name)}, ${mock.farm.hectares}, ${q(mock.farm.location)}, array[${mock.farm.crops.map(q).join(", ")}]);

insert into profile_fields (farm_id, key, value, source, confidence, confirmed_at, valid_until) values
  ${rows(profileFields.map((f) => `(${q(FARM_ID)}, ${q(f.key)}, ${j(f.value)}, ${q(f.source)}, ${q(f.confidence)}, ${q(f.confirmedAt)}, ${q(f.validUntil)})`))};

insert into profile_sections (farm_id, section_id, confirmed_at) values
  ${rows(Object.entries(sectionConfirmations).map(([id, at]) => `(${q(FARM_ID)}, ${q(id)}, ${q(at)})`))};

insert into market_data (metric, observed_on, value, unit, label, source) values
  ${rows(Object.entries(market).map(([metric, m]) => `(${q(metric)}, ${q(m!.date)}, ${m!.value}, ${q(m!.unit)}, ${q(m!.label)}, ${q(m!.source)})`))}
on conflict (metric, observed_on) do update set value = excluded.value, unit = excluded.unit, label = excluded.label, source = excluded.source;

insert into profile_snapshots (id, farm_id, version, taken_at, reason, fields, market, exposures) values
  (${q(SNAPSHOT_ID)}, ${q(FARM_ID)}, 1, ${q(SNAPSHOT_AT)}, ${q(snapshot.reason)}, ${j(snapshot.fields)}, ${j(snapshot.market)}, ${j(snapshot.exposures)});

insert into assessments (id, farm_id, snapshot_id, created_at, harvest_year, summary, risks) values
  (${q(ASSESSMENT_ID)}, ${q(FARM_ID)}, ${q(SNAPSHOT_ID)}, ${q(SNAPSHOT_AT)}, ${mock.meta.harvestYear}, ${j({
    meta: mock.meta,
    profit: mock.profit,
    breakEvens: mock.breakEvens,
    topMitigationIds: mock.topMitigationIds,
  })}, ${j(mock.risks)});

insert into pending_changes (id, farm_id, field_key, field_label, current_value, proposed_value, source, reason, status, received_at) values
  ${rows(
    mock.pendingChanges.map(
      (p) =>
        `(${q(p.id)}, ${q(FARM_ID)}, ${q(p.fieldKey)}, ${q(p.field)}, ${q(p.currentValue)}, ${q(p.proposedValue)}, ${q(p.source)}, ${q(p.reason)}, ${q(p.status)}, ${q(receivedAt[p.id])})`
    )
  )};

insert into signals (id, farm_id, risk_id, kind, title, summary, source, url, published_at, metric, value) values
  ${rows(signals.map((s) => `(${q(s.id)}, null, ${q(s.riskId)}, ${q(s.kind)}, ${q(s.title)}, ${q(s.summary)}, ${q(s.source)}, ${q(s.url)}, ${q(s.publishedAt)}, ${q(s.metric)}, ${n(s.value)})`))};

insert into signal_impacts (signal_id, snapshot_id, farm_id, risk_id, delta, working, alert) values
  ${rows(
    signals.map((s) => {
      const i = measureSignal(s, snapshot);
      return `(${q(s.id)}, ${q(SNAPSHOT_ID)}, ${q(FARM_ID)}, ${q(s.riskId)}, ${n(i.delta)}, ${j(i.working)}, ${i.alert})`;
    })
  )};

commit;
`;

process.stdout.write(sql);
